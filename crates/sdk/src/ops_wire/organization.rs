/// Issue a `CreateOrganization` RPC via the wire transport.
///
/// Mirrors [`LedgerClient::create_organization`](crate::LedgerClient::create_organization)
/// at the dispatch layer. The organization slug is generated by the caller
/// (one slug per logical call, reused across retries) so the server-side
/// idempotency-by-slug path returns the same `OrganizationId` instead of
/// creating a duplicate body on response-lost-in-flight. `request_id` is the
/// 128-bit frame-header correlation ID; the SDK's retry loop is responsible
/// for rotating it across attempts.
///
/// # Errors
///
/// Returns [`SdkError::Connection`] for transport / protocol failures and
/// the appropriate [`SdkError`] variant for server-returned [`WireError`]s
/// (rate-limit family, migration codes, all others land in `Rpc`).
pub(crate) async fn create_organization(
    wire_client: Arc<WireClient>,
    request_id: u128,
    name: String,
    region: Region,
    caller: UserSlug,
    tier: OrganizationTier,
    organization_slug: OrganizationSlug,
) -> Result<OrganizationInfo> {
    let client = OrganizationServiceClient::new(wire_client);
    let request = w::CreateOrganizationRequest {
        name,
        region: region.as_str().to_owned(),
        tier: Some(domain_tier_to_wire(tier)),
        caller: Some(caller),
        slug: Some(organization_slug),
    };
    let response =
        client.create_organization(request, request_id).await.map_err(rpc_error_to_sdk_error)?;
    Ok(domain_organization_info_from_wire_create(response))
}


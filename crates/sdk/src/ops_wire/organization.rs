//! Wire-based OrganizationService ops.
//!
//! Mirrors [`super::super::ops::organization`]: same returned domain types
//! ([`OrganizationInfo`], [`OrganizationDeleteInfo`], [`OrganizationMemberInfo`],
//! [`TeamInfo`], [`MigrationInfo`]), same `Result<_, SdkError>` shape on the
//! consumer side. Internal dispatch goes through the wire-services-generated
//! [`OrganizationServiceClient`](inferadb_ledger_wire_services::OrganizationServiceClient)
//! instead of the proto-generated tonic client.
//!
//! End-to-end coverage with a real `WireClient` + `WireServer` is deferred
//! to E.7 (TestCluster migration); the unit tests in this file cover the
//! wire-response → domain-type mapping (status / tier / role enums, page
//! envelopes, optional `Team` / `OrganizationMember` unwrap) in isolation.
//! The seventeen per-RPC entry points themselves are not exercised yet —
//! [`LedgerClient`](crate::LedgerClient) keeps dispatching through the tonic
//! `ops::organization` path until F.1 flips the connection pool.

use std::{str::FromStr, sync::Arc};

use bytes::Bytes;
use inferadb_ledger_types::{OrganizationSlug, Region, TeamSlug, UserSlug};
use inferadb_ledger_wire::services::{organization as w, shared as ws};
use inferadb_ledger_wire_services::OrganizationServiceClient;
use inferadb_ledger_wire_transport::WireClient;

use crate::{
    error::{Result, SdkError},
    ops_wire::rpc_error_to_sdk_error,
    types::admin::{
        MigrationInfo, OrganizationDeleteInfo, OrganizationInfo, OrganizationMemberInfo,
        OrganizationMemberRole, OrganizationStatus, OrganizationTier, TeamInfo, TeamMemberInfo,
        TeamMemberRole,
    },
};


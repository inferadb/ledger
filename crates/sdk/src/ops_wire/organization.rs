/// Numeric-tag mapping from the wire `OrganizationStatus` to the domain
/// enum. Mirrors the proto-side `OrganizationStatus::from_proto(i32)`.
fn wire_organization_status_to_domain(status: ws::OrganizationStatus) -> OrganizationStatus {
    match status {
        ws::OrganizationStatus::Active => OrganizationStatus::Active,
        ws::OrganizationStatus::Provisioning => OrganizationStatus::Provisioning,
        ws::OrganizationStatus::Migrating => OrganizationStatus::Migrating,
        ws::OrganizationStatus::Suspended => OrganizationStatus::Suspended,
        ws::OrganizationStatus::Deleted => OrganizationStatus::Deleted,
        ws::OrganizationStatus::Unspecified => OrganizationStatus::Unspecified,
    }
}

/// Numeric-tag mapping from the wire `OrganizationTier` to the domain
/// enum. Mirrors the proto-side `OrganizationTier::from_proto(i32)` —
/// `Unspecified` collapses to `Free`, matching the proto path's default.
fn wire_organization_tier_to_domain(tier: ws::OrganizationTier) -> OrganizationTier {
    match tier {
        ws::OrganizationTier::Launch => OrganizationTier::Launch,
        ws::OrganizationTier::Scale => OrganizationTier::Scale,
        // Unspecified + Free both surface as Free — mirrors proto path.
        ws::OrganizationTier::Free | ws::OrganizationTier::Unspecified => OrganizationTier::Free,
    }
}

/// Numeric-tag mapping from the domain `OrganizationTier` to the wire
/// enum, used on outgoing requests.
fn domain_tier_to_wire(tier: OrganizationTier) -> ws::OrganizationTier {
    match tier {
        OrganizationTier::Free => ws::OrganizationTier::Free,
        OrganizationTier::Launch => ws::OrganizationTier::Launch,
        OrganizationTier::Scale => ws::OrganizationTier::Scale,
    }
}


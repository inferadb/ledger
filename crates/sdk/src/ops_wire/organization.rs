/// Issue a `ListOrganizations` RPC via the wire transport.
///
/// Mirrors [`LedgerClient::list_organizations`](crate::LedgerClient::list_organizations).
/// Returns a tuple `(organizations, next_page_token)` where
/// `next_page_token` is `None` when there are no more pages. The SDK
/// exposes the page token as `Vec<u8>` even though the wire type uses
/// `Bytes` — the boundary conversion happens here.
///
/// # Errors
///
/// Same shape as [`create_organization`].
pub(crate) async fn list_organizations(
    wire_client: Arc<WireClient>,
    request_id: u128,
    caller: UserSlug,
    page_size: u32,
    page_token: Option<Vec<u8>>,
) -> Result<(Vec<OrganizationInfo>, Option<Vec<u8>>)> {
    let client = OrganizationServiceClient::new(wire_client);
    let request = w::ListOrganizationsRequest {
        page_token: page_token.map(Bytes::from),
        page_size,
        caller: Some(caller),
    };
    let response =
        client.list_organizations(request, request_id).await.map_err(rpc_error_to_sdk_error)?;
    let organizations =
        response.organizations.into_iter().map(domain_organization_info_from_wire_get).collect();
    let next_page_token = response.next_page_token.map(|b| b.to_vec());
    Ok((organizations, next_page_token))
}


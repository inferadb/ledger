/// Issue a `MigrateOrganization` RPC via the wire transport.
///
/// Mirrors [`LedgerClient::migrate_organization`](crate::LedgerClient::migrate_organization).
/// Returns [`MigrationInfo`] with source / target regions and current
/// status. The wire response carries `source_region` / `target_region` as
/// region-slug strings; this helper falls back to `Region::GLOBAL` /
/// caller-provided `target_region` when the slug doesn't parse — same
/// fail-soft contract as the proto path.
///
/// # Errors
///
/// Same shape as [`create_organization`].
pub(crate) async fn migrate_organization(
    wire_client: Arc<WireClient>,
    request_id: u128,
    slug: OrganizationSlug,
    target_region: Region,
    acknowledge_residency_downgrade: bool,
    caller: UserSlug,
) -> Result<MigrationInfo> {
    let client = OrganizationServiceClient::new(wire_client);
    let request = w::MigrateOrganizationRequest {
        slug: Some(slug),
        target_region: target_region.as_str().to_owned(),
        acknowledge_residency_downgrade,
        caller: Some(caller),
    };
    let response =
        client.migrate_organization(request, request_id).await.map_err(rpc_error_to_sdk_error)?;
    Ok(MigrationInfo {
        slug: response.slug.unwrap_or_else(|| OrganizationSlug::new(0)),
        source_region: parse_region(&response.source_region).unwrap_or(Region::GLOBAL),
        target_region: parse_region(&response.target_region).unwrap_or(target_region),
        status: wire_organization_status_to_domain(response.status),
    })
}


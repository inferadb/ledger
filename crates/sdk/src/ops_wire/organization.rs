/// Parses a wire-format region slug into a domain [`Region`]. Returns
/// `None` for empty or malformed slugs — callers decide the fallback.
fn parse_region(value: &str) -> Option<Region> {
    Region::from_str(value).ok()
}

/// Converts a UNIX-nanoseconds wire timestamp into `SystemTime`.
///
/// Returns `None` for `0` (the wire convention for "unset") and for values
/// that overflow `Duration`. This mirrors the proto path's
/// `proto_timestamp_to_system_time` which returns `None` on absence /
/// invalid inputs.
fn nanos_to_system_time(nanos: u64) -> Option<std::time::SystemTime> {
    if nanos == 0 {
        return None;
    }
    let secs = nanos / 1_000_000_000;
    let subsec_nanos = u32::try_from(nanos % 1_000_000_000).ok()?;
    std::time::UNIX_EPOCH.checked_add(std::time::Duration::new(secs, subsec_nanos))
}

/// Builds the "missing field" `SdkError` shared by single-record wire
/// responses. Mirrors `proto_util::missing_response_field` at the dispatch
/// layer — same `wire ErrorCode::Internal` shape so SDK consumers see one
/// error shape across both transports.
fn missing_field(field: &str, response_type: &str) -> SdkError {
    SdkError::Rpc {
        code: inferadb_ledger_wire::ErrorCode::Internal,
        message: format!("Missing {field} in {response_type}"),
        request_id: None,
        trace_id: None,
        error_details: None,
    }
}

